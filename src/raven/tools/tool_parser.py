"""Tool Parser - robust tool call extraction from model text responses.

Supports:
- XML-style tool calls: <tool_call><name>...</name><arguments>...</arguments></tool_call>
  and <tool_call>{"name": "...", "arguments": {...}}</tool_call>
- Markdown JSON code blocks with "name"/"tool" and "arguments"/"parameters"
- Raw JSON dictionaries with "name" and "arguments"
- Multiple sequential tool calls in a single response
"""

from __future__ import annotations

import json
import re
from typing import Dict, Any, List, Optional


class ToolCall:
    """Represents a tool call parsed from model output."""

    def __init__(self, name: str, arguments: Dict[str, Any], id: Optional[str] = None):
        self.name = name
        self.arguments = arguments
        self.id = id or f"call_{abs(hash(name + str(arguments))) % 1000000}"

    def __getitem__(self, item):
        if item == "name":
            return self.name
        if item == "arguments":
            return self.arguments
        if item == "id":
            return self.id
        raise KeyError(item)

    def get(self, item, default=None):
        try:
            return self[item]
        except KeyError:
            return default

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "arguments": self.arguments,
        }

    def __repr__(self) -> str:
        return f"ToolCall(name={self.name!r}, arguments={self.arguments!r}, id={self.id!r})"


def parse_tool_calls_from_text(content: str) -> List[ToolCall]:
    """Parse tool calls from text response generated by any model.
    
    Returns list of ToolCall instances (which also support dictionary-style access).
    """
    if not content or not content.strip():
        return []

    calls: List[ToolCall] = []

    # 1. XML style: <tool_call> ... </tool_call>
    xml_pattern = re.compile(r"<tool_call>(.*?)</tool_call>", re.DOTALL | re.IGNORECASE)
    for match in xml_pattern.finditer(content):
        block = match.group(1).strip()
        # Check for nested <name> and <arguments> tags
        name_match = re.search(r"<name>(.*?)</name>", block, re.DOTALL | re.IGNORECASE)
        args_match = re.search(r"<arguments>(.*?)</arguments>", block, re.DOTALL | re.IGNORECASE)
        if name_match:
            name = name_match.group(1).strip()
            args = {}
            if args_match:
                raw_args = args_match.group(1).strip()
                try:
                    args = json.loads(raw_args)
                except Exception:
                    # Try finding json in raw_args
                    f_b = raw_args.find("{")
                    l_b = raw_args.rfind("}")
                    if f_b != -1 and l_b > f_b:
                        try:
                            args = json.loads(raw_args[f_b : l_b + 1])
                        except Exception:
                            pass
            calls.append(ToolCall(name=name, arguments=args))
            continue

        # Alternatively, JSON inside <tool_call>
        parsed = _try_parse_tool_json(block)
        if parsed:
            calls.append(parsed)

    if calls:
        return calls

    # 2. Markdown json code blocks: ```json ... ```
    md_pattern = re.compile(r"```(?:json)?\s*(\{\s*[\s\S]*?\})\s*```", re.DOTALL)
    for match in md_pattern.finditer(content):
        raw_json = match.group(1).strip()
        parsed = _try_parse_tool_json(raw_json)
        if parsed:
            calls.append(parsed)

    if calls:
        return calls

    # 3. Direct JSON objects in text
    json_obj_pattern = re.compile(
        r'\{\s*"(?:name|tool|function)"\s*:\s*"([a-zA-Z0-9_\-]+)"\s*,\s*"(?:arguments|parameters|args)"\s*:\s*(\{[\s\S]*?\})\s*\}',
        re.DOTALL,
    )
    for match in json_obj_pattern.finditer(content):
        try:
            full_str = match.group(0)
            data = json.loads(full_str)
            parsed = _normalize_tool_dict(data)
            if parsed:
                calls.append(parsed)
        except Exception:
            continue

    return calls


def _try_parse_tool_json(raw_text: str) -> Optional[ToolCall]:
    """Attempt to parse a raw string as a tool call."""
    try:
        data = json.loads(raw_text)
        if isinstance(data, list) and data:
            data = data[0]
        if isinstance(data, dict):
            return _normalize_tool_dict(data)
    except Exception:
        first_brace = raw_text.find("{")
        last_brace = raw_text.rfind("}")
        if first_brace != -1 and last_brace > first_brace:
            try:
                data = json.loads(raw_text[first_brace : last_brace + 1])
                if isinstance(data, dict):
                    return _normalize_tool_dict(data)
            except Exception:
                pass
    return None


def _normalize_tool_dict(data: Dict[str, Any]) -> Optional[ToolCall]:
    """Normalize extracted dictionary into standard ToolCall."""
    name = data.get("name") or data.get("tool") or data.get("function")
    if not name or not isinstance(name, str):
        return None

    args = data.get("arguments") or data.get("parameters") or data.get("args") or {}
    if isinstance(args, str):
        try:
            args = json.loads(args)
        except Exception:
            args = {}
    if not isinstance(args, dict):
        args = {}

    call_id = data.get("id")

    return ToolCall(
        id=str(call_id) if call_id else None,
        name=name.strip(),
        arguments=args,
    )


def clean_content_after_tool_extraction(content: str) -> str:
    """Remove tool call markup from user-facing text content."""
    cleaned = re.sub(r"<tool_call>[\s\S]*?</tool_call>", "", content, flags=re.DOTALL | re.IGNORECASE)
    cleaned = re.sub(r"```(?:json)?\s*\{\s*\"(?:name|tool)\"[\s\S]*?\}\s*```", "", cleaned, flags=re.DOTALL)
    return cleaned.strip()


def format_tool_definitions_for_prompt(definitions: List[Dict[str, Any]]) -> str:
    """Format tools list for prompt instructions."""
    lines = ["Available Tools:"]
    for t in definitions:
        name = t.get("name", "")
        desc = t.get("description", "")
        lines.append(f"\nTool: {name}")
        lines.append(f"Description: {desc}")
        params = t.get("parameters", {}).get("properties", {})
        if params:
            lines.append("Parameters:")
            for p_name, p_info in params.items():
                p_desc = p_info.get("description", "")
                p_type = p_info.get("type", "any")
                lines.append(f"  - {p_name} ({p_type}): {p_desc}")
    
    lines.append("\nTo use a tool, invoke it like:")
    lines.append("<tool_call>\n<name>tool_name</name>\n<arguments>\n{\"param\": \"value\"}\n</arguments>\n</tool_call>")
    return "\n".join(lines)


def format_tool_results_for_prompt(results: List[Dict[str, Any]]) -> str:
    """Format executed tool results for feedback into prompt."""
    parts = []
    for r in results:
        name = r.get("name", "")
        status = "success" if r.get("success", False) else "failed"
        output = r.get("output", "")
        error = r.get("error")
        content = output if not error else f"{output}\nError: {error}"
        parts.append(f'<tool_result name="{name}" status="{status}">\n{content}\n</tool_result>')
    return "\n\n".join(parts)
